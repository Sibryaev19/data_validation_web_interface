import uvicorn


def main() -> None:
    """
    Точка входа для запуска единого приложения (бэкенд + фронтенд) на одном порту.

    Фронтенд раздаётся как статика из папки `static` внутри FastAPI-приложения `app`.
    """
    uvicorn.run(
        "app:app",
        host="0.0.0.0",
        port=3015,  # единый порт для фронтенда и бэкенда
        reload=True,
    )


if __name__ == "__main__":
    main()


